// Calculate estimated Prime delivery window
export function getPrimeDeliveryEstimate() {
    const date = new Date();
    date.setDate(date.getDate() + 2);
    return date.toLocaleDateString('en-US', { weekday: 'long', month: 'short', day: 'numeric' });
}
